func TestRewrite(t *testing.T) {
	tr := Tree{Dir: "/tmp/algo-test-rust-1", Sources: map[string]string{
		"merge_sort.rs":      "nodes/sorting/merge-sort/impl/rust/merge_sort.rs",
		"merge_sort_test.rs": "nodes/sorting/merge-sort/impl/rust/merge_sort_test.rs",
	}}
	in := "error[E0308]: mismatched types\n  --> merge_sort.rs:14:5\nthread panicked at /tmp/algo-test-rust-1/merge_sort_test.rs:3:9\nsrc/merge_sort.rs:1 stays"
	want := "error[E0308]: mismatched types\n  --> nodes/sorting/merge-sort/impl/rust/merge_sort.rs:14:5\nthread panicked at nodes/sorting/merge-sort/impl/rust/merge_sort_test.rs:3:9\nsrc/merge_sort.rs:1 stays"
	if got := tr.Rewrite(in); got != want {
		t.Errorf("Rewrite:\n%s\nwant\n%s", got, want)
	}
}

func TestWriteScript(t *testing.T) {
	p := filepath.Join(t.TempDir(), "run.sh")
	if err := WriteScript(p, [][]string{{"javac", "-d", "out", "A B.java"}, {"echo", "it's"}}); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(p)
	want := "#!/bin/sh\n# Generated by aik gen. Do not edit.\nset -eu\ncd \"$(dirname \"$0\")\"\njavac -d out 'A B.java'\necho 'it'\\''s'\n"
	if string(b) != want {
		t.Errorf("script:\n%s\nwant\n%s", b, want)
	}
}

func TestGenStagesFixtures(t *testing.T) {
	nd := t.TempDir()
	for name, body := range map[string]string{
		"fixtures/shapes.json":          "{}\n",
		"fixtures/make.py":              "# make\n",
		"fixtures/.hidden":              "no\n",
		"fixtures/__pycache__/make.pyc": "no",
	} {
		p := filepath.Join(nd, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	n := &node.Node{Dir: nd, Rel: "nodes/x/attention", Slug: "attention"}
	got, err := Shared(n)
	if err != nil || strings.Join(got, ",") != "fixtures/make.py,fixtures/shapes.json" {
		t.Fatalf("Shared = %v, %v", got, err)
	}
	if got, err := Shared(&node.Node{Dir: t.TempDir()}); err != nil || len(got) != 0 {
		t.Fatalf("Shared without fixtures = %v, %v", got, err)
	}
	im := node.Impl{Lang: "numpy", Files: []node.File{
		{Name: "attention.py", Path: "nodes/x/attention/impl/numpy/attention.py", Content: "x = 1\n"},
		{Name: "test_attention.py", Path: "nodes/x/attention/impl/numpy/test_attention.py", Content: "def test_x(): pass\n", Test: true},
	}}
	dir := t.TempDir()
	tr, err := (&Runner{}).Gen(dir, n, im)
	if err != nil {
		t.Fatal(err)
	}
	if b, err := os.ReadFile(filepath.Join(dir, "fixtures", "shapes.json")); err != nil || string(b) != "{}\n" {
		t.Errorf("the fixture is not in the tree: %q, %v", b, err)
	}
	if tr.Sources["fixtures/shapes.json"] != "nodes/x/attention/fixtures/shapes.json" {
		t.Errorf("sources: %v", tr.Sources)
	}
}
